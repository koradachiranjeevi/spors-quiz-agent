import sys
import json
from loguru import logger
from fpdf import FPDF
from src import config

def setup_logging():
    """Configures Loguru to output logs to both terminal and a file in the logs/ directory."""
    logger.remove()
    
    # Console logging
    logger.add(
        sys.stdout,
        level="INFO",
        format="<green>{time:YYYY-MM-DD HH:mm:ss}</green> | <level>{level:7}</level> | <cyan>{name}</cyan>:<cyan>{function}</cyan>:<cyan>{line}</cyan> - <level>{message}</level>"
    )
    
    # File logging
    logger.add(
        config.get_log_path(),
        rotation="10 MB",
        retention="30 days",
        level="DEBUG",
        format="{time:YYYY-MM-DD HH:mm:ss} | {level:7} | {name}:{function}:{line} - {message}"
    )
    logger.info("Logging configured successfully.")

def clean_latin1(text: str) -> str:
    """Cleans up text to make sure it only contains characters compatible with PDF latin-1 encoding."""
    if not text:
        return ""
    
    replacements = {
        "\u201c": '"', "\u201d": '"', # Smart double quotes
        "\u2018": "'", "\u2019": "'", # Smart single quotes
        "\u2013": "-", "\u2014": "-", # En/em dashes
        "\u2022": "*",                 # Bullet points
        "\u00a0": " ",                 # Non-breaking space
        "\u00e9": "e", "\u00e8": "e", # Accent characters
        "\u00e1": "a", "\u00ed": "i",
        "\u00f3": "o", "\u00fa": "u",
        "\u00f1": "n",
    }
    
    for orig, repl in replacements.items():
        text = text.replace(orig, repl)
        
    return text.encode('latin-1', errors='replace').decode('latin-1')

class QuizPDF(FPDF):
    def __init__(self, sport: str, difficulty: str):
        super().__init__()
        self.sport = sport
        self.difficulty = difficulty

    def header(self):
        self.set_fill_color(30, 41, 59) # Deep slate theme color
        self.rect(0, 0, 210, 40, 'F')
        
        self.set_text_color(255, 255, 255)
        self.set_font("Helvetica", "B", 18)
        self.set_y(10)
        self.cell(0, 10, "SportIQ - AI Generated Quiz", border=False, ln=True, align="C")
        
        self.set_font("Helvetica", "", 10)
        self.cell(0, 5, f"Sport: {self.sport}  |  Difficulty: {self.difficulty.capitalize()}", border=False, ln=True, align="C")
        self.ln(15)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(128, 128, 128)
        self.cell(0, 10, f"Generated by SportIQ RAG Engine  |  Page {self.page_no()}/{{nb}}", border=False, align="C")

def generate_quiz_pdf(quiz_data: dict, sport: str, difficulty: str) -> bytes:
    """Generates a styled PDF containing the quiz and a separate answer sheet. Returns PDF as bytes."""
    pdf = QuizPDF(sport, difficulty)
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.alias_nb_pages()
    
    # ------------------ PAGE 1: QUESTIONS ------------------
    pdf.add_page()
    pdf.set_y(45)
    pdf.set_text_color(30, 41, 59)
    
    pdf.set_font("Helvetica", "B", 14)
    pdf.cell(0, 10, "Quiz Questions", border=False, ln=True)
    pdf.ln(3)
    
    questions = quiz_data.get("questions", [])
    for idx, q in enumerate(questions, 1):
        # Prevent page breaks in the middle of a question if possible
        pdf.set_font("Helvetica", "B", 11)
        question_text = clean_latin1(f"{idx}. {q.get('question', '')}")
        pdf.multi_cell(0, 6, question_text)
        pdf.ln(2)
        
        pdf.set_font("Helvetica", "", 10)
        options = q.get("options", {})
        for label in ["A", "B", "C", "D"]:
            opt_val = options.get(label, "")
            opt_text = clean_latin1(f"   [{label}]  {opt_val}")
            pdf.multi_cell(0, 5, opt_text)
        pdf.ln(5)
        
    # ------------------ PAGE 2: ANSWER KEY ------------------
    pdf.add_page()
    pdf.set_y(45)
    pdf.set_text_color(30, 41, 59)
    
    pdf.set_font("Helvetica", "B", 14)
    pdf.cell(0, 10, "Answer Key & Explanations", border=False, ln=True)
    pdf.ln(3)
    
    for idx, q in enumerate(questions, 1):
        pdf.set_font("Helvetica", "B", 11)
        pdf.cell(0, 6, clean_latin1(f"Question {idx}: {q.get('question', '')[:60]}..."), border=False, ln=True)
        
        pdf.set_font("Helvetica", "B", 10)
        pdf.set_text_color(16, 185, 129) # green accent
        correct_answer = q.get("answer", "")
        options = q.get("options", {})
        correct_text = options.get(correct_answer, "")
        pdf.cell(0, 5, clean_latin1(f"Correct Answer: {correct_answer} - {correct_text}"), border=False, ln=True)
        
        pdf.set_text_color(30, 41, 59) # restore text color
        pdf.set_font("Helvetica", "I", 9)
        explanation = clean_latin1(f"Explanation: {q.get('explanation', '')}")
        pdf.multi_cell(0, 4.5, explanation)
        pdf.ln(5)
        
    return pdf.output()

def generate_quiz_json_bytes(quiz_data: dict) -> bytes:
    """Converts the quiz dictionary to pretty JSON formatted bytes for downloading."""
    try:
        json_str = json.dumps(quiz_data, indent=2)
        return json_str.encode('utf-8')
    except Exception as e:
        logger.error(f"Failed to convert quiz to JSON bytes: {e}")
        return b""
